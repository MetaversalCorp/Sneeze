/***********************************************************************************************************************************
**  SOCKET Impl Class
***********************************************************************************************************************************/

class SOCKET::Impl : public ISOCKET_LINK
{
public:
   Impl (SOCKET* pSocket, SOCKET_HUB* pHub, CONTAINER* pContainer, uint32_t nSocketIx, const std::string& sUrl, const std::string& sProtocol) :
      ISOCKET_LINK        (),
      m_pSocket           (pSocket),
      m_pHub              (pHub),
      m_pContainer        (pContainer),
      m_nSocketIx         (nSocketIx),
      m_sUrl              (sUrl),
      m_sProtocol_Request (sProtocol),
      m_bState            (kSOCKET_STATE_CLOSED),
      m_pListener         (nullptr)
   {
   }

   ~Impl ()
   {
      // Detach first. It is the hub's guarantee that no callback is running and
      // none ever will again, which is what makes tearing down the rest safe.
      m_pHub->Detach (this);
   }

   bool Initialize (ISOCKET* pListener)
   {
      bool bResult = false;

      {
         std::lock_guard<std::mutex> guard (m_mxSocket);

         m_pListener = pListener;
         m_bState    = kSOCKET_STATE_CONNECTING;
      }

      bResult = m_pHub->Connect (this, m_sUrl, m_sProtocol_Request);

      if (!bResult)
      {
         std::lock_guard<std::mutex> guard (m_mxSocket);

         m_bState = kSOCKET_STATE_CLOSED;
         m_sError = "not a WebSocket URL, or the connection could not be created";
      }

      return bResult;
   }

   bool Send (const uint8_t* pData, size_t nSize, bool bBinary)
   {
      bool bResult = false;

      if (nSize <= kSOCKET_FRAME_MAX  &&  State () == kSOCKET_STATE_OPEN)
         bResult = m_pHub->Send (this, pData, nSize, bBinary);

      return bResult;
   }

   void Close (uint16_t wCode, const std::string& sReason)
   {
      bool bClose = false;

      {
         std::lock_guard<std::mutex> guard (m_mxSocket);

         if (m_bState == kSOCKET_STATE_CONNECTING  ||  m_bState == kSOCKET_STATE_OPEN)
         {
            m_bState = kSOCKET_STATE_CLOSING;
            bClose   = true;
         }
      }

      if (bClose)
         m_pHub->Close (this, wCode, Reason_Trim (sReason));
   }

   eSOCKET_STATE State () const
   {
      std::lock_guard<std::mutex> guard (m_mxSocket);

      return m_bState;
   }

   std::string Protocol () const
   {
      std::lock_guard<std::mutex> guard (m_mxSocket);

      return m_sProtocol;
   }

   std::string Error () const
   {
      std::lock_guard<std::mutex> guard (m_mxSocket);

      return m_sError;
   }

   ISOCKET* Listener () const
   {
      std::lock_guard<std::mutex> guard (m_mxSocket);

      return m_pListener;
   }

   // -----------------------------------------------------------------------
   // ISOCKET_LINK - all four arrive on the hub's io thread, with the hub's
   // entry lock held. m_mxSocket is released before the listener is called so
   // it stays a leaf: the listener is free to read back off the socket.
   // -----------------------------------------------------------------------

   void OnOpened (const std::string& sProtocol) override
   {
      ISOCKET* pListener = nullptr;

      {
         std::lock_guard<std::mutex> guard (m_mxSocket);

         m_bState    = kSOCKET_STATE_OPEN;
         m_sProtocol = sProtocol;
         pListener   = m_pListener;
      }

      if (pListener)
         pListener->OnSocketOpened (m_pSocket);
   }

   void OnMessage (const uint8_t* pData, size_t nSize, bool bBinary) override
   {
      ISOCKET* pListener = Listener ();

      if (pListener)
         pListener->OnSocketMessage (m_pSocket, pData, nSize, bBinary);
   }

   void OnFailed (const std::string& sError) override
   {
      ISOCKET* pListener = nullptr;

      {
         std::lock_guard<std::mutex> guard (m_mxSocket);

         m_bState  = kSOCKET_STATE_CLOSED;
         m_sError  = sError;
         pListener = m_pListener;
      }

      // The browser's shape: the error is reported, and then the socket closes
      // with 1006 (abnormal closure) because no closing handshake happened.
      if (pListener)
      {
         pListener->OnSocketFailed (m_pSocket);
         pListener->OnSocketClosed (m_pSocket, 1006, false);
      }
   }

   void OnClosed (uint16_t wCode, bool bClean) override
   {
      ISOCKET* pListener = nullptr;

      {
         std::lock_guard<std::mutex> guard (m_mxSocket);

         m_bState  = kSOCKET_STATE_CLOSED;
         pListener = m_pListener;
      }

      if (pListener)
         pListener->OnSocketClosed (m_pSocket, wCode, bClean);
   }

   SOCKET*                                            m_pSocket;
   SOCKET_HUB*                                        m_pHub;
   CONTAINER*                                         m_pContainer;
   uint32_t                                           m_nSocketIx;
   std::string                                        m_sUrl;
   std::string                                        m_sProtocol_Request;

   mutable std::mutex                                 m_mxSocket;
   eSOCKET_STATE                                      m_bState;
   std::string                                        m_sProtocol;
   std::string                                        m_sError;
   ISOCKET*                                           m_pListener;
};

