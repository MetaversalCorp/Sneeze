namespace SNEEZE
{
   // The Mozilla CA bundle compiled into the library (generated by
   // src/CMakeLists.txt). The fetch path only needs it on platforms with no
   // trust store of their own; BoringSSL never has one, so every socket
   // verifies against this.
   extern const char*  const g_szCaCertPem;
   extern const unsigned long g_nCaCertPemLen;
}

using namespace SNEEZE;

typedef websocketpp::client<websocketpp::config::asio_tls_client> CLIENT_TLS;
typedef websocketpp::client<websocketpp::config::asio_client>     CLIENT_PLAIN;

// The protocol allows 123 bytes of close reason. Truncating blindly can split a
// UTF-8 sequence, which the transport then rejects and the close fails outright,
// so any trailing partial sequence goes with it.

static std::string Reason_Trim (const std::string& sReason)
{
   std::string sResult = sReason.substr (0, 123);

   while (!sResult.empty ()  &&  (static_cast<unsigned char> (sResult.back ()) & 0xC0) == 0x80)
      sResult.pop_back ();

   // What is left is either whole or ends on a lead byte with its continuation
   // bytes cut off, which is the one case the loop above cannot see.
   if (!sResult.empty ()  &&  (static_cast<unsigned char> (sResult.back ()) & 0xC0) == 0xC0)
      sResult.pop_back ();

   return sResult;
}

// The TLS context every wss:// connection gets. websocketpp sets SNI itself from
// the connection's URI; the host name check is ours to install.

static std::shared_ptr<asio::ssl::context> Tls_Context (CLIENT_TLS* pClient, websocketpp::connection_hdl hdl)
{
   std::shared_ptr<asio::ssl::context> pContext = std::make_shared<asio::ssl::context> (asio::ssl::context::tls_client);

   websocketpp::lib::error_code ec;

   pContext->set_options (asio::ssl::context::default_workarounds | asio::ssl::context::no_sslv2 | asio::ssl::context::no_sslv3, ec);
   pContext->set_verify_mode (asio::ssl::verify_peer, ec);
   pContext->add_certificate_authority (asio::const_buffer (g_szCaCertPem, g_nCaCertPemLen), ec);

   CLIENT_TLS::connection_ptr pConn = pClient->get_con_from_hdl (hdl, ec);

   if (pConn  &&  pConn->get_uri ())
      pContext->set_verify_callback (asio::ssl::host_name_verification (pConn->get_uri ()->get_host ()), ec);

   return pContext;
}

