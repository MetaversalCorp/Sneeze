bool SOCKET::Send_Binary (const uint8_t* pData, size_t nSize)    { return m_pImpl->Send (pData, nSize, true); }

void SOCKET::Close (uint16_t wCode, const std::string& sReason) { m_pImpl->Close (wCode, sReason); }

eSOCKET_STATE      SOCKET::State    () const { return m_pImpl->State (); }
uint64_t           SOCKET::Buffered () const { return m_pImpl->m_pHub->Buffered (m_pImpl); }
const std::string& SOCKET::Url      () const { return m_pImpl->m_sUrl; }
std::string        SOCKET::Protocol () const { return m_pImpl->Protocol (); }
std::string        SOCKET::Error    () const { return m_pImpl->Error (); }

