SOCKET::SOCKET (SOCKET_HUB* pHub, CONTAINER* pContainer, uint32_t nSocketIx, const std::string& sUrl, const std::string& sProtocol) :
   m_pImpl (new Impl (this, pHub, pContainer, nSocketIx, sUrl, sProtocol))
{
}

SOCKET::~SOCKET ()
{
   delete m_pImpl;
}

bool SOCKET::Initialize (ISOCKET* pListener) { return m_pImpl->Initialize (pListener); }

